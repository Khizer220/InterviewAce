import { FaArrowRight } from "react-icons/fa";
import InterviewCard from "../InterviewCard/InterviewCard";
import "./AvailableInterviews.css";
import { useNavigate } from "react-router-dom";

const AvailableInterviews = ({
  interviews,
  loading,
  onStartInterview,
}) => {
  const navigate = useNavigate();
  return (
    <section className="available-wrapper">

      <div className="available-header">

        <div className="available-left">

          <span className="section-tag">
            AI Interview Library
          </span>

          <h2>Available Interviews</h2>

          <p>
            Practice real interview questions generated by AI.
          </p>

        </div>

       <button
  className="view-all-btn"
  onClick={() => navigate("/candidate/interviews")}
>
  View All
  <FaArrowRight />
</button>

      </div>

      {loading ? (

        <div className="available-loading">
          Loading interviews...
        </div>

      ) : interviews.length === 0 ? (

        <div className="available-loading">
          No interview templates available.
        </div>

      ) : (

        <>
          <div className="available-slider">

            <div className="available-grid">

              {interviews.map((interview) => (

                <InterviewCard
                  key={interview._id}
                  interview={interview}
                  onStart={() => onStartInterview(interview)}
                />

              ))}

            </div>

          </div>

          <div className="slider-dots">

            <span className="active"></span>

            <span></span>

            <span></span>

          </div>

        </>

      )}

    </section>
  );
};

export default AvailableInterviews;